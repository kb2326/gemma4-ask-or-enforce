"""Every number in the paper's tables, computed from experiments/<run>/results.csv and trace_stats.csv.

Usage:  python analysis/paper_tables.py          # writes docs/paper/tables.md and prints it
Nothing in the paper's tables is typed by hand; rerun this after any change to the CSVs.
"""

import csv
import json
import random
import re
import statistics
from pathlib import Path

from compare import BOOTSTRAP_N, BOOTSTRAP_SEED, bootstrap_ci
from heldout_tests import TIMEOUT

REPO = Path(__file__).resolve().parent.parent
EXPERIMENTS = REPO / 'experiments'

DEV = [('Reference', ['practice30-baseline', 'e0', 'e2']), ('E3.1', ['e3_1', 'e3_1_r2']), ('E5', ['e5']),
       ('E5b', ['e5b', 'e5b_r2']), ('ORACLE', ['oracle', 'oracle_r2'])]
HELDOUT = [('E2', 'e2_h41'), ('E3.1', 'e3_1_h41'), ('E5b', 'e5b_h41'), ('ORACLE', 'oracle_h41')]


def read(run, name):
    return list(csv.DictReader(open(EXPERIMENTS / run / name, encoding='utf-8')))


def arm_row(results, stats):
    """One run's counts. A writer is a task with any file write; source-first means that first write was source."""
    unsolved = [s for s in stats if s['solved'] != 'True']
    finder = [float(s['finder_seconds']) for s in stats if float(s.get('finder_runs') or 0) > 0]
    scratch = [s for s in stats if s['first_write_kind'] == 'scratch']
    return {'tasks': len(stats), 'solved': sum(s['solved'] == 'True' for s in stats),
            'timeouts': sum(r['error'].startswith(TIMEOUT) for r in results),
            'writers': sum(bool(s['first_write_kind']) for s in stats),
            'source_first': sum(s['first_write_kind'] == 'source' for s in stats),
            'scratch': len(scratch), 'scratch_tmp': sum(s['first_write_in_tmp'] == 'True' for s in scratch),
            'no_source_edit': sum(s['patch_overlap'] == 'empty' for s in unsolved),
            'wrong_files_only': sum(s['patch_overlap'] == 'none' for s in unsolved),
            'localizer_median_s': round(statistics.median(finder), 1) if finder else None}


def run_row(run):
    return arm_row(read(run, 'results.csv'), read(run, 'trace_stats.csv'))


def dev_rows():
    return [(name, [run_row(r) for r in runs]) for name, runs in DEV]


def heldout_rows():
    return [(name, run_row(run)) for name, run in HELDOUT]


def sign_flip_greater(diffs, n=BOOTSTRAP_N, seed=BOOTSTRAP_SEED):
    """One-sided paired permutation p-value that the mean per-task difference is above zero (random sign flips)."""
    observed = sum(diffs)
    if not any(diffs):
        return 1.0
    rng = random.Random(seed)
    hits = sum(sum(d if rng.random() < 0.5 else -d for d in diffs) >= observed - 1e-12 for _ in range(n))
    return (hits + 1) / (n + 1)


def per_task_source_first(runs):
    """Per task, the share of an arm's runs whose first write was a source edit (no write counts as 0)."""
    stats = [{s['task']: s['first_write_kind'] == 'source' for s in read(run, 'trace_stats.csv')} for run in runs]
    tasks = set.intersection(*(set(s) for s in stats))
    return {t: sum(s[t] for s in stats) / len(stats) for t in tasks}


def dev_task_level(new_runs, ref_runs):
    """Development comparison with each task counted once: per-task means over runs, paired by task."""
    new, ref = per_task_source_first(new_runs), per_task_source_first(ref_runs)
    tasks = sorted(set(new) & set(ref))
    diffs = [new[t] - ref[t] for t in tasks]
    return {'tasks': len(tasks), 'diff': sum(diffs) / len(diffs), 'ci95': bootstrap_ci(diffs),
            'p': sign_flip_greater(diffs)}


def pct(a, b):
    return f'{a}/{b} ({100 * a / b:.0f}%)' if b else '-'


def table_md():
    out = ['# Paper tables (generated by analysis/paper_tables.py; do not edit by hand)', '',
           '## Table 1. Development set, 30 tasks per run', '',
           '| Arm (runs) | Solved | Source-first (all tasks) | Source-first / writing tasks | Scratch-first under /tmp '
           '| Unsolved, no source edit | Unsolved, wrong files only | Timeouts | Localizer median |',
           '|---|---|---|---|---|---|---|---|---|']
    for name, rows in dev_rows():
        joined = lambda k: ', '.join(str(r[k]) for r in rows)
        total = lambda k: sum(r[k] for r in rows)
        loc = ', '.join(f"{r['localizer_median_s']:g} s" for r in rows if r['localizer_median_s'] is not None) or '-'
        out.append(f"| {name} ({len(rows)}) | {joined('solved')} | {pct(total('source_first'), total('tasks'))} | "
                   f"{pct(total('source_first'), total('writers'))} | {pct(total('scratch_tmp'), total('scratch'))} | "
                   f"{joined('no_source_edit')} | {joined('wrong_files_only')} | {joined('timeouts')} | {loc} |")
    runs = dict(DEV)
    out += ['', 'Task-level comparison with the reference (each task counted once: per-task share of runs that were '
            'source-first, paired by task; mean difference, 95% bootstrap CI, one-sided sign-flip permutation p): ' +
            '; '.join(f"{name} {100 * r['diff']:+.1f} pp [{100 * r['ci95'][0]:+.1f}, {100 * r['ci95'][1]:+.1f}], "
                      f"p = {r['p']:.3f}" for name, r in
                      ((n, dev_task_level(runs[n], runs['Reference'])) for n in ('E3.1', 'E5', 'E5b', 'ORACLE'))) + '.']
    out += ['', '## Table 2. Held-out set, 41 tasks, one run per arm (confirmatory)', '',
            '| Arm | Solved | Source-first (all tasks) | Source-first / writing tasks | Scratch-first under /tmp '
            '| Unsolved, no source edit | Unsolved, wrong files only | Timeouts | Localizer median |',
            '|---|---|---|---|---|---|---|---|---|']
    for name, r in heldout_rows():
        loc = f"{r['localizer_median_s']:g} s" if r['localizer_median_s'] is not None else '-'
        out.append(f"| {name} | {r['solved']}/{r['tasks']} | {r['source_first']}/{r['tasks']} | "
                   f"{pct(r['source_first'], r['writers'])} | {pct(r['scratch_tmp'], r['scratch'])} | "
                   f"{r['no_source_edit']} | {r['wrong_files_only']} | {r['timeouts']} | {loc} |")
    t = json.loads((EXPERIMENTS / 'heldout_tests.json').read_text())
    c1, c2, c3 = t['C1'], t['C2'], t['C3']
    out += ['', '## Table 3. Pre-registered held-out tests (fixed sequence C1 -> C2 -> C3)', '',
            '| Claim | Statistic | Status |', '|---|---|---|',
            f"| C1 /tmp compliance | E3.1 {c1['e31_tmp_share']:.0%} vs E2 {c1['e2_tmp_share']:.0%}; one-sided Fisher "
            f"p = {c1['p']:.1e} | {c1['status']} |",
            f"| C2 structure raises source-first | E5b {c2['e5b_source_first']} vs E2 {c2['e2_source_first']} of "
            f"{t['tasks']}; b = {c2['b']}, c = {c2['c']}; one-sided McNemar p = {c2['p']:.2f}; writers-only Fisher "
            f"p = {c2['sensitivity_writers_fisher_p']:.2f}; manipulation check (localizer median "
            f"{c2['localizer_median_s']:g} s <= 60 s) {'met' if c2['localizer_check'] else 'not met'}; per repo "
            + ', '.join(f"{repo} {v['E5b']} vs {v['E2']}" for repo, v in t['per_repo_source_first'].items())
            + f" | {c2['status']} |",
            f"| C3 location bound < +15 pp | ORACLE - E2 = {100 * c3['diff']:+.1f} pp, one-sided upper bound "
            f"{100 * c3['upper']:+.1f} pp | {c3['status']} |", '',
            'Estimates (source-first difference, 95% bootstrap CI): ' + '; '.join(
                f"{k} {100 * v['diff']:+.1f} pp [{100 * v['ci95'][0]:+.1f}, {100 * v['ci95'][1]:+.1f}]"
                for k, v in t['estimates'].items()) + '.']
    return '\n'.join(out) + '\n'


def fill_draft(draft, tables):
    """Replace the body between each '<!-- TABLE n -->' and '<!-- /TABLE n -->' pair with Table n from tables."""
    for section in re.split(r'\n## (?=Table \d)', tables)[1:]:
        n = section.split('.')[0].split()[-1]
        title, rest = section.split('\n', 1)
        body = f'**{title}**\n' + rest.rstrip('\n') + '\n'
        draft = re.sub(rf'(<!-- TABLE {n} -->\n).*?(<!-- /TABLE {n} -->)', lambda m: m[1] + body + m[2], draft,
                       flags=re.S)
    return draft


if __name__ == '__main__':
    text = table_md()
    (REPO / 'docs' / 'paper' / 'tables.md').write_text(text, encoding='utf-8')
    draft = REPO / 'docs' / 'paper' / 'draft.md'
    draft.write_text(fill_draft(draft.read_text(encoding='utf-8'), text), encoding='utf-8')
    print(text)
